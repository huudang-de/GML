    (SELECT dso FROM dso_calc) AS dso,
    (SELECT dio FROM dio_calc) AS dio,
    (SELECT dpo FROM dpo_calc) AS dpo,
    ((SELECT dso FROM dso_calc) + (SELECT dio FROM dio_calc) - (SELECT dpo FROM dpo_calc)) AS ccc;

