                       OR account_no LIKE '34113%'
                       OR account_no LIKE '34114%' THEN credit_amount - debit_amount
                  ELSE 0
              END) AS delta_ngan_han,
          SUM(CASE
                  WHEN account_no LIKE '34112%' THEN credit_amount - debit_amount
